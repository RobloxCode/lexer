#include <stdio.h>

int main(void) {
    /* Unsigned int: U */
    int n1 = 10u;
    int n2 = 10U;

    /* Long int: L */
    int n3 = 10l;
    int n4 = 10L;

    /* Unsigned long int: UL / LU */
    int n5 = 10ul;
    int n6 = 10uL;
    int n7 = 10Ul;
    int n8 = 10UL;
    int n9 = 10lu;
    int n10 = 10lU;
    int n11 = 10Lu;
    int n12 = 10LU;

    /* Long long int: LL */
    int n13 = 10ll;
    int n14 = 10LL;

    /* Unsigned long long int: ULL / LLU */
    int n15 = 10ull;
    int n16 = 10uLL;
    int n17 = 10Ull;
    int n18 = 10ULL;
    int n19 = 10llu;
    int n20 = 10llU;
    int n21 = 10LLu;
    int n22 = 10LLU;

    long double f3 = 10.0f;
    long double f4 = 10.0F;

    double f5 = 38.8lf;

    return 0;
}
